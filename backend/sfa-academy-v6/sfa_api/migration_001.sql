

CREATE TABLE IF NOT EXISTS students(student TEXT PRIMARY KEY, alias TEXT NOT NULL,
 enrollment_hash TEXT UNIQUE NOT NULL, telegram BIGINT UNIQUE, stage INTEGER NOT NULL DEFAULT 1, current_week INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS sessions(hash TEXT PRIMARY KEY, student TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS links(hash TEXT PRIMARY KEY, student TEXT NOT NULL, expires INTEGER NOT NULL, used INTEGER DEFAULT 0);
CREATE TABLE IF NOT EXISTS quizzes(attempt TEXT PRIMARY KEY, student TEXT NOT NULL, digest TEXT NOT NULL, body TEXT NOT NULL, created INTEGER NOT NULL, assessment TEXT, week INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS events(id TEXT PRIMARY KEY, student TEXT NOT NULL, kind TEXT NOT NULL, body TEXT NOT NULL, created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS submissions(id TEXT PRIMARY KEY, student TEXT NOT NULL, stage INTEGER NOT NULL,
 state TEXT NOT NULL, created INTEGER NOT NULL, week INTEGER NOT NULL DEFAULT 1);
CREATE UNIQUE INDEX IF NOT EXISTS one_draft ON submissions(student) WHERE state='DRAFT';
CREATE TABLE IF NOT EXISTS files(id TEXT PRIMARY KEY, submission TEXT NOT NULL, path TEXT NOT NULL, text_path TEXT,
 digest TEXT NOT NULL, name TEXT NOT NULL, size INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS decisions(id TEXT PRIMARY KEY, submission TEXT UNIQUE NOT NULL, body TEXT NOT NULL,
 digest TEXT NOT NULL, state TEXT NOT NULL, approved INTEGER NOT NULL DEFAULT 0, message_id BIGINT);
CREATE TABLE IF NOT EXISTS weeks(student TEXT NOT NULL, week INTEGER NOT NULL, stage INTEGER NOT NULL,
 state TEXT NOT NULL, attempt TEXT, assignment TEXT, quiz_verdict TEXT, practical_verdict TEXT,
 PRIMARY KEY(student,week));
CREATE TABLE IF NOT EXISTS mentor_decisions(id TEXT PRIMARY KEY, target TEXT UNIQUE NOT NULL, student TEXT NOT NULL,
 week INTEGER NOT NULL, kind TEXT NOT NULL, body TEXT NOT NULL, digest TEXT NOT NULL, state TEXT NOT NULL,
 approved INTEGER NOT NULL DEFAULT 0, message_id BIGINT);
CREATE TABLE IF NOT EXISTS weaknesses(student TEXT NOT NULL,id TEXT NOT NULL,skill TEXT NOT NULL,first_week INTEGER NOT NULL,
 evidence TEXT NOT NULL,status TEXT NOT NULL,last_drilled INTEGER,clean_weeks INTEGER NOT NULL DEFAULT 0,last_clean_week INTEGER,
 PRIMARY KEY(student,id));
CREATE TABLE IF NOT EXISTS nonces(nonce TEXT PRIMARY KEY, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS rate(key TEXT PRIMARY KEY, start INTEGER NOT NULL, count INTEGER NOT NULL);

