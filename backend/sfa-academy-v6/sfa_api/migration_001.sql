ALTER TABLE mentor_decisions ADD COLUMN IF NOT EXISTS snapshot TEXT;
ALTER TABLE mentor_decisions ADD COLUMN IF NOT EXISTS override_reason TEXT;
CREATE SEQUENCE IF NOT EXISTS student_number START 10000;
CREATE TABLE IF NOT EXISTS invites(hash TEXT PRIMARY KEY, expires BIGINT NOT NULL, max_uses INTEGER NOT NULL, uses INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS resets(hash TEXT PRIMARY KEY, student TEXT NOT NULL, expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS claims(request TEXT PRIMARY KEY, lease TEXT NOT NULL, expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS notifications(id TEXT PRIMARY KEY, student TEXT NOT NULL, body TEXT NOT NULL, created BIGINT NOT NULL, is_read INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS outbox(id TEXT PRIMARY KEY, chat BIGINT NOT NULL, body TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'PENDING', tries INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS responses(student TEXT NOT NULL, stage INTEGER NOT NULL, body TEXT NOT NULL, PRIMARY KEY(student,stage));
CREATE TABLE IF NOT EXISTS legacy_imports(path TEXT PRIMARY KEY, imported BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY, value TEXT NOT NULL);
